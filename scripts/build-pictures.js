// Builds src/pictures.js, the pictures that come with Pitwall, from the ones set in a Pitwall save: real drivers'
// photos and full-body pictures, team logos, cars and each team's default driver, the default driver, the trophies
// and the graphics' logo. Pictures of your own driver, your own drivers and teams (and My Team) are left out, and a
// picture removed in the save doesn't take one out of the set: the set only grows or changes.
//   node scripts/build-pictures.js <path to career-data.json>
const fs = require('fs'); const path = require('path');
const OUT = path.join(__dirname, '..', 'src', 'pictures.js');
const file = process.argv[2]; if (!file) throw new Error('give the path to career-data.json');
const S = JSON.parse(fs.readFileSync(file, 'utf8')); const st = S.state || S; const im = st.images || {};
const cur = fs.existsSync(OUT) ? new Function(fs.readFileSync(OUT, 'utf8') + ';return DEFAULT_IMAGES;')() : {};
const out = { drivers: {}, teams: {}, cars: {}, bodies: {}, teamBodies: {}, ...cur };
// your own: a career's driver (careerId:id), drivers you made (C + six characters), teams you made (T-…), My Team
const own = (id) => id.includes(':') || /^C[0-9a-z]{6}$/i.test(id) || /^T-/.test(id) || id === 'myteam';
const n = {};
for (const kind of ['drivers', 'teams', 'cars']) for (const [id, url] of Object.entries(im[kind] || {})) if (url && !own(id)) { out[kind][id] = url; n[kind] = (n[kind] || 0) + 1; }
for (const [id, b] of Object.entries(im.bodies || {})) if (b?.url && !own(id)) { out.bodies[id] = { url: b.url, look: b.look || 'center' }; n.bodies = (n.bodies || 0) + 1; }
for (const [id, b] of Object.entries(im.teamBodies || {})) if (b?.url && !own(id)) { out.teamBodies[id] = { url: b.url, look: b.look || 'center' }; n.teamBodies = (n.teamBodies || 0) + 1; }
if (im.defaultBody?.url) { out.defaultBody = { url: im.defaultBody.url, look: im.defaultBody.look || 'center' }; n.defaultBody = 1; }
for (const k of ['driver', 'team']) if (st.gfxTrophy?.[k]) { (out.trophy ||= {})[k] = st.gfxTrophy[k]; n.trophy = (n.trophy || 0) + 1; }
if (st.gfxLogo) { out.logo = st.gfxLogo; n.logo = 1; }
fs.writeFileSync(OUT, `/* Pitwall — the pictures that come with the app: real drivers' photos and full-body pictures, team logos, cars and
   default drivers, the default driver, the trophies and the graphics' logo. Yours (uploaded, or removed) take their
   place; your own driver and drivers, your own teams and My Team keep theirs on the career.
   Generated by scripts/build-pictures.js. */
'use strict';
const DEFAULT_IMAGES = ${JSON.stringify(out)};
`);
console.log(`Wrote src/pictures.js (${Math.round(fs.statSync(OUT).size / 1024)} KB): taken from the save`, n,
  '· in all', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, typeof v === 'string' ? 1 : Object.keys(v).length])));
